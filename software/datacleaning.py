import pandas as pd
import numpy as np


# ============================================================
# 1. 读取 CSV 数据
# ============================================================

# pd.read_csv()：
# 用于读取 CSV 文件，并将数据保存为 Pandas 的 DataFrame。
# r"..." 表示原始字符串，可以避免 Windows 路径中的反斜杠
# 被 Python 当作特殊转义字符处理。
df = pd.read_csv(r"D:\Desktop\NUS\EE5003\Dataset\Health_Risk_Dataset.csv")


# ============================================================
# 2. 检查数据基本规模
# ============================================================

# df.shape 返回一个元组：
# 第一个值是数据行数，第二个值是数据列数。
rows, columns = df.shape

print("========== 1. 数据规模 ==========")
print("数据行数:", rows)
print("数据列数:", columns)


# ============================================================
# 3. 查看列名
# ============================================================

# df.columns 返回 DataFrame 中所有列的名称。
print("\n========== 2. 列名 ==========")
print(df.columns.tolist())


# ============================================================
# 4. 检查数据类型
# ============================================================

# df.dtypes 可以查看每一列的数据类型。
# int64      -> 整数
# float64    -> 浮点数
# object     -> 通常表示字符串/类别数据
print("\n========== 3. 数据类型 ==========")
print(df.dtypes)


# ============================================================
# 5. 检查缺失值
# ============================================================

# df.isnull()：
# 判断每一个数据是否为空。
#
# .sum()：
# 对 True/False 进行统计。
# True 会被当成 1，False 会被当成 0。
#
# 因此可以得到每一列缺失值的数量。
print("\n========== 4. 缺失值 ==========")
print(df.isnull().sum())


# ============================================================
# 6. 检查重复数据
# ============================================================

# df.duplicated()：
# 判断每一行是否是重复行。
#
# .sum()：
# 统计重复行的数量。
print("\n========== 5. 重复数据 ==========")
print("重复行数量:", df.duplicated().sum())


# ============================================================
# 7. 检查每一列有多少种不同的取值
# ============================================================

# df.nunique()：
# 统计每一列有多少个不同的值。
#
# 这个步骤对于判断：
#   - 连续变量
#   - 二元变量
#   - 类别变量
# 非常有用。
print("\n========== 6. 不同取值数量 ==========")
print(df.nunique())


# ============================================================
# 8. 检查类别型变量的具体取值
# ============================================================

# value_counts()：
# 统计每一个类别出现了多少次。
#
# 这里重点检查 Consciousness 和 Risk_Level。
print("\n========== 7. Consciousness 分布 ==========")
print(df["Consciousness"].value_counts())

print("\n========== 8. Risk_Level 分布 ==========")
print(df["Risk_Level"].value_counts())


# ============================================================
# 9. 检查数值特征的统计范围
# ============================================================

# describe()：
# 自动计算数值型数据的统计信息，包括：
# count -> 数据数量
# mean  -> 平均值
# std   -> 标准差
# min   -> 最小值
# 25%   -> 第一四分位数
# 50%   -> 中位数
# 75%   -> 第三四分位数
# max   -> 最大值
print("\n========== 9. 数值特征统计 ==========")
print(df.describe())


# ============================================================
# 10. 检查每个输入特征是否存在异常范围
# ============================================================

# 定义真正用于 KNN 的 8 个输入特征。
# Patient_ID 不属于机器学习输入。
feature_columns = [
    "Respiratory_Rate",
    "Oxygen_Saturation",
    "O2_Scale",
    "Systolic_BP",
    "Heart_Rate",
    "Temperature",
    "Consciousness",
    "On_Oxygen"
]

# 输出每个输入特征的基本信息。
print("\n========== 10. 输入特征检查 ==========")

for column in feature_columns:

    # 取得当前列。
    data = df[column]

    print("\n特征:", column)
    print("数据类型:", data.dtype)
    print("不同取值数量:", data.nunique())

    # 如果当前列是数值类型，则检查最小值和最大值。
    if pd.api.types.is_numeric_dtype(data):

        print("最小值:", data.min())
        print("最大值:", data.max())

    # 如果不是数值类型，则输出所有类别。
    else:

        print("类别:", data.unique())


# ============================================================
# 11. 最终检查结果
# ============================================================

print("\n\n========== 最终结论 ==========")

print("数据规模:", df.shape)
print("输入特征数量:", len(feature_columns))
print("输出变量: Risk_Level")
print("输出类别数量:", df["Risk_Level"].nunique())

print("\n缺失值总数:", df.isnull().sum().sum())
print("重复行数量:", df.duplicated().sum())

